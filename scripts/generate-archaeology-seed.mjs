#!/usr/bin/env node
// Generates idempotent SQL for the archaeology catalog from
// data/archaeology/findings.json, validating every finding first (verse
// references against the KJV, coordinates, ratings, source counts):
//
//   node scripts/generate-archaeology-seed.mjs > data/archaeology/findings.seed.sql
//
// Production gets a snapshot of this output as a migration. Local
// `supabase db reset` runs migrations before seeds, when books don't exist
// yet, so the migration inserts no scripture refs there; this seed file
// (listed after kjv.seed.sql in supabase/config.toml) fills them in.

import { readFileSync } from "node:fs";

const read = (path) =>
  JSON.parse(readFileSync(new URL(path, import.meta.url), "utf8"));

const kjv = read("../data/kjv/kjv.normalized.json");
const { findings } = read("../data/archaeology/findings.json");

const RATINGS = new Set(["established", "supported", "debated", "unverified"]);
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** slug → { osisId, chapters: Map<chapter, verseCount> } */
const books = new Map(
  kjv.books.map((b) => [b.slug, { osisId: b.osisId, chapters: new Map() }]),
);
const byOsis = new Map([...books.values()].map((b) => [b.osisId, b]));
for (const v of kjv.verses) {
  const { chapters } = byOsis.get(v.book);
  chapters.set(v.chapter, Math.max(chapters.get(v.chapter) ?? 0, v.verse));
}

const errors = [];
const fail = (slug, message) => errors.push(`${slug}: ${message}`);

/** "18:13" → [18, 13], checked against the book's chapters and verses. */
function parsePoint(slug, book, text) {
  const match = /^(\d+):(\d+)$/.exec(text);
  if (!match) {
    fail(slug, `bad reference "${text}"`);
    return [0, 0];
  }
  const [chapter, verse] = [Number(match[1]), Number(match[2])];
  const verses = books.get(book)?.chapters.get(chapter);
  if (!verses || verse < 1 || verse > verses) {
    fail(slug, `${book} ${text} doesn't exist`);
  }
  return [chapter, verse];
}

const nonEmpty = (value) => typeof value === "string" && /\S/.test(value);
const seen = new Set();

for (const f of findings) {
  const slug = f.slug;
  if (!SLUG.test(slug ?? "") || seen.has(slug)) fail(slug, "bad or duplicate slug");
  seen.add(slug);
  for (const field of ["title", "summary", "siteName", "credibilityNote"]) {
    if (!nonEmpty(f[field])) fail(slug, `missing ${field}`);
  }
  if (!Array.isArray(f.description) || !f.description.every(nonEmpty)) {
    fail(slug, "description must be a list of paragraphs");
  }
  if (!RATINGS.has(f.credibility)) fail(slug, `bad rating "${f.credibility}"`);
  if (!(Math.abs(f.lat) <= 90 && Math.abs(f.lng) <= 180)) fail(slug, "bad coordinates");
  if (!f.refs?.length) fail(slug, "no scripture refs");
  if (!(f.sources?.length >= 3)) fail(slug, "needs at least 3 sources");
  if (!f.timeline?.length) fail(slug, "no timeline");

  f.parsedRefs = (f.refs ?? []).map((ref) => {
    if (!books.has(ref.book)) fail(slug, `unknown book "${ref.book}"`);
    const [cs, vs] = parsePoint(slug, ref.book, ref.from);
    const [ce, ve] = parsePoint(slug, ref.book, ref.to);
    if (ce < cs || (ce === cs && ve < vs)) fail(slug, `${ref.from}–${ref.to} runs backward`);
    return { book: ref.book, cs, vs, ce, ve };
  });
  for (const s of f.sources ?? []) {
    if (!nonEmpty(s.citation)) fail(slug, "source without a citation");
    if (s.url !== null && !/^https:\/\/\S+$/.test(s.url ?? "")) {
      fail(slug, `bad source url "${s.url}"`);
    }
  }
  (f.timeline ?? []).forEach((t, i, list) => {
    if (!Number.isInteger(t.year) || !nonEmpty(t.label) || !nonEmpty(t.event)) {
      fail(slug, `bad timeline entry "${t.label}"`);
    }
    if (i > 0 && t.year < list[i - 1].year) fail(slug, `timeline out of order at "${t.label}"`);
  });
}

if (errors.length) {
  process.stderr.write(`${errors.join("\n")}\n`);
  process.exit(1);
}

const q = (s) => (s === null ? "null" : `'${s.replaceAll("'", "''")}'`);
const rows = (list) => list.map((cells) => `  (${cells.join(", ")})`).join(",\n");
const slugList = findings.map((f) => q(f.slug)).join(", ");

const out = [
  "-- Generated by scripts/generate-archaeology-seed.mjs from data/archaeology/findings.json; do not edit by hand.",
  "",
  "insert into public.findings (slug, title, summary, description, site_name, location_lat, location_lng, credibility_rating, credibility_note, sort_order) values",
  rows(
    findings.map((f, i) => [
      q(f.slug),
      q(f.title),
      q(f.summary),
      q(f.description.join("\n\n")),
      q(f.siteName),
      f.lat,
      f.lng,
      q(f.credibility),
      q(f.credibilityNote),
      i + 1,
    ]),
  ),
  "on conflict (slug) do update set title = excluded.title, summary = excluded.summary,",
  "  description = excluded.description, site_name = excluded.site_name,",
  "  location_lat = excluded.location_lat, location_lng = excluded.location_lng,",
  "  credibility_rating = excluded.credibility_rating, credibility_note = excluded.credibility_note,",
  "  sort_order = excluded.sort_order, updated_at = now();",
  "",
  `delete from public.findings where slug not in (${slugList});`,
  "",
  "-- Children are replaced wholesale so removed entries disappear too.",
  `delete from public.finding_scripture_refs where finding_id in (select id from public.findings where slug in (${slugList}));`,
  `delete from public.finding_sources where finding_id in (select id from public.findings where slug in (${slugList}));`,
  `delete from public.finding_timeline where finding_id in (select id from public.findings where slug in (${slugList}));`,
  "",
  "insert into public.finding_scripture_refs (finding_id, position, book_id, chapter_start, verse_start, chapter_end, verse_end)",
  "select f.id, v.position, b.id, v.cs, v.vs, v.ce, v.ve",
  "from (values",
  rows(
    findings.flatMap((f) =>
      f.parsedRefs.map((r, i) => [q(f.slug), i + 1, q(r.book), r.cs, r.vs, r.ce, r.ve]),
    ),
  ),
  ") as v (slug, position, book, cs, vs, ce, ve)",
  "join public.findings f on f.slug = v.slug",
  "join public.books b on b.slug = v.book;",
  "",
  "insert into public.finding_sources (finding_id, position, citation, url)",
  "select f.id, v.position, v.citation, v.url",
  "from (values",
  rows(
    findings.flatMap((f) =>
      f.sources.map((s, i) => [q(f.slug), i + 1, q(s.citation), q(s.url)]),
    ),
  ),
  ") as v (slug, position, citation, url)",
  "join public.findings f on f.slug = v.slug;",
  "",
  "insert into public.finding_timeline (finding_id, position, year, label, event)",
  "select f.id, v.position, v.year, v.label, v.event",
  "from (values",
  rows(
    findings.flatMap((f) =>
      f.timeline.map((t, i) => [q(f.slug), i + 1, t.year, q(t.label), q(t.event)]),
    ),
  ),
  ") as v (slug, position, year, label, event)",
  "join public.findings f on f.slug = v.slug;",
  "",
];

process.stdout.write(out.join("\n"));
